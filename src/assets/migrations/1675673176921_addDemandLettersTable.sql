
CREATE TABLE IF NOT EXISTS demand_letters (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name VARCHAR(255) NOT NULL,
  app_ref VARCHAR(255) NOT NULL,
  internal_ref VARCHAR(255) NOT NULL,
  date_opened VARCHAR(255) NOT NULL,
  status VARCHAR(255),
  online_ref VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(255) NOT NULL,
  updated_by VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS demand_letter_details (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  demand_letter_id INTEGER NOT NULL,
  name VARCHAR(255) NOT NULL,
  detail VARCHAR(255) NOT NULL,
  online_ref VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(255) NOT NULL,
  updated_by VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS demand_letter_workorders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  demand_letter_id INTEGER NOT NULL,
  workorder_id INTEGER NOT NULL,
  online_ref VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by VARCHAR(255) NOT NULL,
  updated_by VARCHAR(255) NOT NULL
);
