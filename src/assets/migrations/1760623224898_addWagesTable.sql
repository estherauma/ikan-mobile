CREATE TABLE IF NOT EXISTS wages (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  online_ref VARCHAR(255),
  user_id VARCHAR(255) NOT NULL,
  vessel_id VARCHAR(255) NOT NULL,
  payment_date VARCHAR(255) NOT NULL,
  start_date VARCHAR(255) NOT NULL,
  end_date VARCHAR(255) NOT NULL,
  usd_amount VARCHAR(255) NOT NULL,
  payslip VARCHAR(255),
  crew_bank_transfer_receipt VARCHAR(255),
  beneficiary_bank_transfer_receipt VARCHAR(255),
  beneficiary_relationship VARCHAR(255),
  beneficiary_name VARCHAR(255),
  beneficiary_contact VARCHAR(255),
  beneficiary_contact_platform VARCHAR(255),
  status VARCHAR(30) DEFAULT 'action_required',
  crew_received_right_amount VARCHAR(10),
  beneficiary_received_right_amount VARCHAR(10),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_at TIMESTAMP DEFAULT NULL,
  created_by VARCHAR(255) NOT NULL,
  updated_by VARCHAR(255) NOT NULL,
  deleted_by VARCHAR(255),
  deleted BOOLEAN DEFAULT 0
);
